// Video-prompt writing rules distilled from Emily2040/seedance-2.0 (MIT): the Director's Read,
// direct-for-the-model, the compact prompt templates, anti-slop and the quality checklist.

export const SEEDANCE_GUIDE = `【视频提示词方法：Seedance 2.0（提炼自 Emily2040/seedance-2.0）】
一、先做导演解读（只写进「生成思路」，不要写进提示词）
- 先判断类型：剧情（有选择、隐瞒、关系变化、转折）→ 写清：这一镜的戏剧作用、前后转变、谁的视角、主导权变化、隐藏的目的、阻碍与对策、潜台词、一个被压住的小动作、一个只属于这个故事的细节、拒绝的套路（如：悲伤就哭特写加配乐）。
- 观察/表演（舞蹈、氛围、动作展示）或功能展示（产品、步骤）→ 只写一句要让观众看到/感到什么，和一句不要强加的戏（不编造冲突、心理）。
- 解读里的抽象词（视角、潜台词、主导权…）不能出现在提示词里，要翻译成镜头能拍到、能听到的东西：机位、视线、手上的动作、道具、空间远近、光、声音、沉默。
二、提示词写法
- 第一句写主体；一个镜头只有一个主要动作，并写出看得见的终点状态；其他人保持各自的小动作（低声交谈、看向门口），不要写「所有人一动不动」。
- 只用一个主镜头运动，写清起点、速度、和主体的关系、终点（如：从中景缓慢推近到手部特写后停住）。
- 光要有物理来源：写光源、方向、颜色（如：头顶一盏暖黄吊灯、左侧冷色窗光），不写「温暖的氛围」。
- 情绪写成「一个直白的情绪词 + 一个身体锚点」（如：他愣住，惊慌，眼睛盯着门口，喉结动了一下），不用成语和比喻（「脸沉下来」「目光如刀」会被字面画出来）。
- 声音要有意图：环境声、动作音效、对白（短句、加引号、说话时头部稳定）或「无配乐」。
- 不写空洞的拔高词（史诗级、大片感、超高清、电影感拉满），换成具体的光、材质和镜头终点。
- 不要把意外结果写成终点（衣角被门夹住、滑倒、打翻），模型会演成故意的；写人物主动的动作，或让后果发生在画外。
- 场面大的东西放在模型擅长的地方：天气、光、布料、尘土、水、火、远处人群；人与人、人与机械的接触保持简单、单一。
三、多镜头与连续性
- 一条提示词里有多个镜头时按事件顺序编号：「镜头1：…，镜头2：切至…」，不在块里写绝对秒数；每个镜头末尾写一行「锁定」：同一光源和颜色、每个主要人物的年龄段/发型/服装/特征道具、各自相对固定地标的位置和朝向、机位在哪一侧。
- 反应镜头是反打：机位站在被看的东西那一侧，人物视线越过镜头看向它；人物从一处到另一处必须在画面里走过去，不能瞬移。
- 道具动作写成手的动作（右手拿起茶杯，杯沿碰到嘴唇），结尾写画面能容纳的状态。
四、参考图
- 每张参考图只担一个主要角色：身份、首帧、尾帧、产品、环境、动作、运镜、风格；写明哪些不能迁移。参考标签原样使用（@图片1、@图片2…），不改写、不翻译。
- 图生视频：@图片1为首帧/参考，严格保持主体、服装、产品不变，只改变动作、光线和镜头。首尾帧：@图片1为首帧，@图片2为尾帧，动作连续不跳切。
五、长度与模板
- 单镜头提示词约 40–110 字（中文可更短），短而具体：主体 → 动作与终点 → 场景 → 镜头 → 光 → 声音 → 约束。
- 文生视频：[主体][动作与终点]在[场景]。镜头：[一个运动]。光：[物理光源]。声音：[提示]。约束：[风险/连续性]。
- 图生视频：@图片1为参考，严格保持[主体]不变；仅加入[动作/光线/镜头]。声音：[提示]。
- 分镜：镜头1：[运镜或切镜]，[动作与表情]，[声音]。镜头2：镜头切至[机位]，[动作与终点]，[声音]。保持无字幕。
六、交付前自检：是否只有一个可见动作、一个主镜头运动、物理光源、声音意图、连续性锁定、约束；有知名 IP、真人肖像、品牌或敏感词（武器、受伤、犯罪、未成年人危险）时改写成原创描述并在思路里说明。`;

/** The task for a video-prompt node. */
export function vpromptTask(params: Record<string, ParamValue>, shotCount: number) {
  const secs = Number(params.duration ?? 5);
  const ratio = String(params.ratio ?? '16:9');
  const en = params.lang === 'English';
  const scope = shotCount
    ? `为上面的分镜脚本逐镜写视频生成提示词，一共 ${shotCount} 条，与分镜一一对应。`
    : '根据上面的创意和素材写视频生成提示词：一个完整的镜头写 1 条；创意里明显有几段不同的画面时，按段落各写 1 条（最多 6 条）。';
  return `${scope}
每条对应一段约 ${secs} 秒、画幅 ${ratio} 的视频；提示词用${en ? '英文' : '中文'}写。
有参考图时按【参考图清单】里的编号写 @图片N，并在提示词标题里写明它的作用（首帧/身份/产品/风格…）；没有参考图就写文生视频。
严格遵循上面的【视频提示词方法：Seedance 2.0】，以及连入的风格、特效、角色和视频玩法。`;
}

/** Output format appended to text, script and video-prompt tasks: reasoning first, then the result. */
export function reasonedFormat(kind: 'text' | 'script' | 'vprompt', resultSpec: string) {
  const extra = kind === 'vprompt' ? '\n- 写出导演解读：这一组镜头属于哪种类型、要让观众看到/感到什么、拒绝了什么套路、每张参考图承担什么角色。' : '';
  return `请严格按下面的格式输出，不要输出其他内容：
【生成思路】
- 逐条说明：每一个连入的素材（按它的名称）你读到了什么关键信息，以及具体用在了结果的哪里；没用上的素材也要说明原因。
- 用户的要求在结果里怎么落实；做了哪些取舍。${extra}
（每条一行，以「- 」开头，简洁具体，让人能对照结果检查。）
【结果】
${resultSpec}`;
}
